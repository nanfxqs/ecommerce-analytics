import { test, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
test.skip(!process.env.REPLAY_CONTROLS_LIVE, 'Requires operator-configured real cluster API');
test('pause keeps consumer running, continue sends suffix, early stop stays incomplete', async ({ page }) => {
  test.setTimeout(300000);
  await page.goto('/'); await page.getByText('实时监控', { exact: true }).click();
  await page.getByRole('spinbutton', { name: '每秒速率' }).fill('2');
  await page.getByRole('button', { name: '启动回放', exact: true }).click();
  await expect(page.getByRole('button', { name: '暂停发送', exact: true })).toBeEnabled({ timeout: 60000 });
  await page.getByRole('button', { name: '暂停发送', exact: true }).click();
  await expect(page.getByText('已暂停发送 · 消费继续', { exact: true })).toBeVisible({ timeout: 60000 });
  const paused = await (await page.request.get('/api/replay/current')).json();
  expect(paused.confirmed).toBeGreaterThan(0);
  expect(paused.confirmed).toBeLessThan(61);
  expect(paused.lag).toBeGreaterThan(0);
  await expect.poll(async () => (await (await page.request.get('/api/replay/current')).json()).lag, { timeout: 180000, intervals: [2000] }).toBe(0);
  const drained = await (await page.request.get('/api/replay/current')).json();
  expect(drained.phase).toBe('paused'); expect(drained.confirmed).toBe(paused.confirmed);
  await page.getByRole('button', { name: '继续发送', exact: true }).click();
  await expect(page.getByRole('button', { name: '提前停止', exact: true })).toBeEnabled({ timeout: 60000 });
  await page.getByRole('button', { name: '提前停止', exact: true }).click();
  await expect(page.getByText('提前停止 · 结果不完整', { exact: true })).toBeVisible({ timeout: 120000 });
  const stopped = await (await page.request.get('/api/replay/current')).json();
  expect(stopped.complete).toBe(false); expect(stopped.early_stopped).toBe(true); expect(stopped.lag).toBe(0); expect(stopped.stream_released).toBe(true);
  expect(stopped.confirmed).toBeGreaterThan(paused.confirmed);
  expect(stopped.confirmed).toBeLessThan(61);
  await page.reload(); await page.getByText('实时监控', { exact: true }).click();
  await expect(page.getByText('提前停止 · 结果不完整', { exact: true })).toBeVisible();
  mkdirSync('../docs/evidence/v2-controls', { recursive: true });
  writeFileSync('../docs/evidence/v2-controls/smoke.json', JSON.stringify({ paused, drained, stopped }, null, 2));
});
